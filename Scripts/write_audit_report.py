from pathlib import Path
import json, csv, re

project=Path(__file__).resolve().parents[1]
root=project/'Saved'/'PortalAudit'
data=json.loads((root/'analysis.json').read_text())
perf=data['performance']
labels={'frozen_capture':'Замороженный вид (база)','live_capture':'Живой портал, неподвижная камера','moving_view':'Движение и поворот камеры','traversal':'Повторные телепортации','traversal_60fps':'Проходы с лимитом 60 FPS','fast_traversal_30fps':'Проходы 2400 см/с с лимитом 30 FPS'}
table='\n'.join(f"| {labels[name]} | {p['mean_fps']:.1f} | {p['p99_ms']:.2f} | {p['max_ms']:.2f} | {p['mean_captures']:.3f} |" for name,p in perf.items())
visual='\n'.join(f"| {name} | {p['core_mean_error_255']:.3f} | {p['core_p95_error_255']:.3f} |" for name,p in data.items() if name!='performance')
samples=list(csv.DictReader((root/'frames.csv').open(encoding='utf-8-sig')))
crossings=[i for i,r in enumerate(samples) if r['crossed']=='1' and r['scenario']=='traversal']
crossing_max=max(float(samples[j]['frame_ms']) for i in crossings for j in range(max(0,i-2),min(len(samples),i+3)))
uncapped={k:v for k,v in perf.items() if k not in ('traversal_60fps','fast_traversal_30fps')}
log=(project/'Saved'/'PortalAudit.log').read_text(encoding='utf-8',errors='replace')
total_crossings=re.findall(r'AUDIT_CAMERA max_error_cm=([\d.]+) traversals=(\d+)',log)[-1]
report=f'''# Проверка порталов — 16.09.2026

В проверенных ракурсах перспектива и параллакс соответствуют прямому виду из связанной точки.
Исходная версия содержала ошибки у ближней плоскости и лишний рендер невидимого портала;
они исправлены. Добавлены три уровня рекурсивного вида, отдельные камеры и render targets
для каждого уровня. Устранено исчезновение объектов из-за общей истории отсечения,
а также наложение поверхностей и щели над рамами.

## Условия

- UE 5.7.2, Development Editor binary в режиме `-game`.
- NVIDIA GeForce RTX 5060 Ti, Intel Core i7-13700KF.
- Реальный GPU-рендеринг вне экрана (`-RenderOffscreen`), не NullRHI.
- **1920×1080**, принудительно через `-ForceRes`, подтверждено размером PNG и логом viewport.
- ScreenPercentage=100, динамическое разрешение и VSync выключены. Первые четыре сценария без лимита FPS;
  два последних намеренно ограничены 60/30 FPS для проверки перехода на крупных шагах времени.
- Три уровня рендера: 1440×810, 720×405, 360×203 при Full HD.
- В каждом сценарии 2 секунды прогрева и 10 секунд измерений.
- В статистику не входят сохранение скриншотов, загрузка карты и начальная компиляция шейдеров.
- Время кадров измерено монотонными системными часами; GPU — через RHIGetGPUFrameCycles.

## Производительность

| Сценарий | Средний FPS | P99 кадра, мс | Максимум, мс | Capture на кадр |
|---|---:|---:|---:|---:|
{table}

Из {sum(p['frames'] for p in uncapped.values())} измеренных кадров без ограничения FPS
{sum(p['frames_over_16_67ms'] for p in uncapped.values())} превысили 16.67 мс,
{sum(p['frames_over_33_33ms'] for p in uncapped.values())} превысили 33.33 мс.
В ограниченных сценариях ожидание лимитера включено во время кадра и не является стоимостью рендера.
P99 — время, в которое уложились 99% кадров, а не минимальный FPS.
Базовый сценарий оставляет ту же поверхность с замороженной текстурой и отключает SceneCapture.

Всего за три сценария выполнено {total_crossings[1]} телепортаций.
В неограниченном сценарии {len(crossings)} попали в измеряемый интервал после прогрева.
Максимальное расхождение положения игровой камеры и камеры персонажа: {total_crossings[0]} см.
Максимум времени кадра в окне ±2 кадра вокруг измеренных телепортаций: {crossing_max:.3f} мс.
Лог содержит скорости до и после преобразования для обычного и ускоренного прохода.

Эти результаты относятся к маленькой тестовой комнате и прогретой сессии без вывода на монитор.
Они не измеряют задержку мышь–монитор, поведение VSync, packaged build, тяжёлые уровни,
холодную загрузку и произвольные конфигурации порталов. Утверждать «никогда не лагает» на их основании нельзя.

## Проверка проекции

Для каждого ракурса сохранены два кадра: изображение портала и обычный viewport из
преобразованной точки камеры. В эталоне скрыты поверхность и стена выхода,
чтобы не перекрывать лучи между виртуальной камерой и плоскостью выхода.
Положение эталонной камеры использует ту же PortalMath, а изображение формируется
обычным главным viewport; вложенный портал рендерится на один уровень меньше,
так как первый переход уже заменён прямой камерой. Это проверка соответствия рендера;
математика преобразований дополнительно покрыта существующим Automation-тестом.

Проверены центр, боковой угол, расстояние 5 см, расстояние 5 мм, точное положение на плоскости,
наклон вниз и FOV=110°. Контуры объектов в открытой области совпадают с эталоном.

| Ракурс | Средняя разница RGB (0–255) | P95 разницы RGB |
|---|---:|---:|
{visual}

Это разница цвета, **не** ошибка координат в пикселях. Используется внутренняя область
проёма, чтобы исключить настоящие боковины рамы, перекрывающие изображение под углом.
Полная маска проёма и её метрики тоже сохранены в analysis.json: у краёв расхождение выше,
так как в эталоне скрыта рама выхода, а в портале она видима. Текстура имеет разрешение 75%
от viewport, поэтому сглаживание мелких контуров отличается от прямого рендера.
Вложенные уровни имеют ещё меньшее разрешение и фильтруются повторно. Поэтому мелкие
далёкие рамки заметно мягче прямого эталона; это ограничение качества при текущем
NestedResolutionScale=0.5, а не обещание попиксельного совпадения рекурсивного изображения.
Для повышения чёткости NestedResolutionScale можно увеличить до 0.75–1.0 ценой нагрузки на GPU.

## Исправления

1. Одиночная плоскость исчезала ближе NearClipPlane=1 см. Теперь поверхность — тонкий объём:
   передняя грань остаётся на портале, задние грани сохраняют изображение у камеры.
2. При проекции всех углов за камерой код продолжал CaptureScene. Теперь такой портал
   отсеивается, с исключением для камеры точно на плоскости, где координата W=0.
3. У рамы и стены совпадали внутренние поверхности и мерцали при наклонном взгляде.
   Размеры блоков стены исправлены, геометрия больше не накладывается; щели над рамой закрыты.
4. Рекурсия ограничена 1–4 уровнями (по умолчанию 3). Каждый уровень имеет собственную
   историю видимости и текстуру; обработка идёт от глубины к поверхности без чтения из
   текущей записываемой текстуры. Последний уровень закрывается чёрным материалом.

## Доказательства и повторение

- `Saved/PortalAudit/comparison.png` — все пары кадров и усиленная разница.
- `Saved/PortalAudit/*_portal.png`, `*_reference.png` — исходные Full HD кадры.
- `Saved/PortalAudit/frames.csv` — время каждого кадра, GPU, число захватов и события перехода.
- `Saved/PortalAudit/analysis.json` — полные числовые результаты.
- `Saved/PortalAudit.log` — условия, замеры, проходы и завершение теста.
- `RunAudit.ps1` — повторный запуск проверки; после него `Scripts/write_audit_report.py` обновляет этот отчёт.

Сохраняются ограничения прототипа: заранее размещённые вертикальные порталы,
один игрок, без физических объектов и произвольного размещения. Рекурсия конечная:
проём на последнем уровне чёрный. Рендер рассчитан на одну связанную пару порталов.
'''
(project/'AUDIT.md').write_text(report,encoding='utf-8')
